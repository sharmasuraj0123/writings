def esc(value) -> str:
    return html.escape(str(value), quote=True)


def text_parts(value) -> list[str]:
    if value is None:
        return []
    if isinstance(value, (list, tuple)):
        return [str(item) for item in value if item is not None and str(item)]
    return [str(value)] if str(value) else []


def text(value) -> str:
    return " ".join(text_parts(value))


def paragraphs(value, default="") -> str:
    return "".join(f"<p>{esc(p)}</p>" for p in (text_parts(value) or text_parts(default)))


def type_text(value) -> str:
    return " | ".join(text_parts(value)) or "type not established"


def slug(key: str, identity: str) -> str:
    label = re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", key).lower()
    label = re.sub(r"[^a-z0-9]+", "-", label).strip("-") or "entry"
    if key.startswith("<") and key.endswith(">"):
        label = "each-" + label
    digest = hashlib.sha256(identity.encode("utf-8")).hexdigest()[:10]
    return f"{label[:24].rstrip('-')}--{digest}"


def derived_path(parent: str, key: str) -> str:
    return parent.rstrip("/") + "/" + key.replace("~", "~0").replace("/", "~1")


def prepare_tree(raw: dict) -> tuple[dict, list[dict]]:
    nodes = []
    paths = set()

    def visit(value, parent=None):
        if not isinstance(value, dict):
            raise ValueError("each object node must be a JSON object")
        node = dict(value)
        if not node.get("key"):
            raise ValueError("every node needs a key")
        node["path"] = str(node.get("path") or (derived_path(parent["path"], str(node["key"])) if parent else "/"))
        if node["path"] in paths:
            raise ValueError(f"duplicate sanitized path: {node['path']}")
        paths.add(node["path"])
        node["parent"] = parent
        node["folder"] = (parent["folder"] / slug(str(node["key"]), node["path"])) if parent else Path()
        node["leaves"] = []
        for raw_leaf in value.get("leaves", []):
            if not isinstance(raw_leaf, dict) or not raw_leaf.get("key"):
                raise ValueError(f"leaf needs a key inside {node['path']}")
            leaf = dict(raw_leaf)
            leaf["path"] = str(leaf.get("path") or derived_path(node["path"], str(leaf["key"])))
            if leaf["path"] in paths:
                raise ValueError(f"duplicate sanitized path: {leaf['path']}")
            paths.add(leaf["path"])
            leaf["anchor"] = "key-" + slug(str(leaf["key"]), leaf["path"])
            node["leaves"].append(leaf)
        nodes.append(node)
        node["children"] = [visit(child, node) for child in value.get("children", [])]
        return node

    return visit(raw), nodes


def rel_link(origin: dict, destination: dict, anchor="") -> str:
    target = destination["folder"] / "index.html"
    value = os.path.relpath(target, origin["folder"]).replace(os.sep, "/")
    return value + ("#" + anchor if anchor else "")


def site_link(node: dict, relative: str) -> str:
    return "../" * (len(node["folder"].parts) + 2) + relative


def badge(value) -> str:
    label = text(value) or "observed"
    cls = "recon" if "infer" in label.lower() else "src"
    return f'<span class="{cls}">{esc(label)}</span>'


def evidence_label(item: dict):
    return item.get("badge") or item.get("evidence")


def source_id(source: dict) -> str:
    return "source-" + slug(str(source["id"]), str(source["id"]))


def evidence(value, sources: dict) -> str:
    refs = text_parts(value)
    if not refs:
        return "No direct reference is supplied for this field."
    result = []
    for ref in refs:
        if ref in sources:
            result.append(f'<a href="#{esc(source_id(sources[ref]))}">[{esc(ref)}]</a>')
        else:
            result.append(esc(ref))
    return "; ".join(result)


def field_facts(item: dict, sources: dict, *, object_node=False) -> str:
    meaning = item.get("meaning") or (item.get("summary") if object_node else None)
    rows = [
        ("Type", f"<code>{esc(type_text(item.get('type')))}</code>"),
        ("Full path", f"<code>{esc(item['path'])}</code>"),
    ]
    if item.get("presence") is not None:
        rows.append(("Presence", esc(text(item["presence"]))))
    rows.extend([
        ("Meaning", paragraphs(meaning, "Meaning is not established by the supplied evidence.")),
        ("Behavior", paragraphs(item.get("behavior"), "Read/write behavior is not established by the supplied evidence.")),
        ("Evidence", badge(evidence_label(item)) + " " + evidence(item.get("source"), sources)),
        ("Limits", paragraphs(item.get("limits"), "The observed type and key name alone do not establish every permitted value or runtime behavior.")),
    ])
    return '<dl class="explorer-facts">' + "".join(f"<div><dt>{esc(label)}</dt><dd>{body}</dd></div>" for label, body in rows) + "</dl>"


def section_list(node: dict, content: dict) -> list[dict]:
    sections = [dict(id="introduction", title="What this object holds", kind="overview")]
    if node["parent"] is None:
        for item in content.get("intro_sections", []):
            if not isinstance(item, dict) or not item.get("id") or not item.get("title"):
                raise ValueError("each intro section needs id and title")
            sections.append(dict(id=str(item["id"]), title=str(item["title"]), kind="intro", content=item))
    sections.append(dict(id="objects", title="Objects and folders", kind="objects"))
    if node["parent"] is None:
        sections += [dict(id="object-map", title="The complete object tree", kind="tree"),
                     dict(id="key-index", title="Find an object or leaf", kind="search")]
    sections += [dict(id=leaf["anchor"], title=str(leaf["key"]), kind="leaf", leaf=leaf) for leaf in node["leaves"]]
    sections.append(dict(id="sources", title="Sources and limits", kind="sources"))
    ids = [s["id"] for s in sections]
    if len(ids) != len(set(ids)):
        raise ValueError(f"duplicate heading id on {node['path']}")
    if any(not re.fullmatch(r"[A-Za-z][A-Za-z0-9_-]*", sid) for sid in ids):
        raise ValueError("section ids must start with a letter and use only letters, digits, hyphens, or underscores")
    for number, section in enumerate(sections, 1):
        prefix = f"{number:02d} · "
        section["number"] = f"{number:02d}"
        section["label"] = prefix + section["title"]
        remaining = 28 - len(prefix)
        title = section["title"]
        section["short"] = prefix + (title if len(title) <= remaining else title[:remaining-1].rstrip() + "…")
    return sections


def navigation(sections: list[dict]) -> tuple[str, str]:
    floating = "".join(f'<a class="toc-parent" href="#{esc(s["id"])}">{esc(s["label"])}</a>' for s in sections)
    rail = "".join(f'<a href="#{esc(s["id"])}" title="{esc(s["label"])}">{esc(s["short"])}</a>' for s in sections)
    chrome = f'''<div class="floating-toc" aria-label="Floating contents"><button class="toc-button" type="button" aria-expanded="false" aria-controls="toc-menu"><span aria-hidden="true">☰</span><span class="toc-button-label">{esc(sections[0]['label'])}</span></button><nav class="toc-menu" id="toc-menu" aria-label="Article sections">{floating}</nav></div>
<aside class="contents-rail" aria-label="Contents"><p class="contents-rail-title">Contents</p><nav aria-label="Article contents">{rail}</nav></aside>'''
    flow = '<nav class="toc" aria-label="Article sections"><p class="toc-title">On this page</p><ol>' + "".join(f'<li><a href="#{esc(s["id"])}">{esc(s["title"])}</a></li>' for s in sections) + "</ol></nav>"
    return chrome, flow


def object_index(node: dict) -> str:
    if not node["children"]:
        detail = "Its direct leaves are explained below." if node["leaves"] else "No child fields were observed; the empty container does not establish a future member schema."
        return f'<p class="explorer-empty">This object has no nested object folders in the supplied snapshot. {detail}</p>'
    rows = []
    for child in node["children"]:
        rows.append(f'<tr><td><a class="explorer-dir" href="{esc(rel_link(node, child))}"><code>{esc(child["key"])}</code><span class="slash">/</span></a></td><td>{esc(type_text(child.get("type")))}</td><td>{esc(text(child.get("summary")))} {badge(evidence_label(child))}</td></tr>')
    return '<div class="table-wrap"><table class="explorer-object-table"><thead><tr><th scope="col">Object folder</th><th scope="col">Type</th><th scope="col">What it holds</th></tr></thead><tbody>' + "".join(rows) + "</tbody></table></div>"


def object_tree(root: dict) -> str:
    def branch(node):
        children = "".join(branch(child) for child in node["children"])
        count = len(node["leaves"])
        label = f'<a class="explorer-dir" href="{esc(rel_link(root, node))}">{esc(node["key"])}<span class="slash">/</span></a> <span class="leaf-count">{count} direct {"leaf" if count == 1 else "leaves"}</span>'
        if children:
            opened = " open" if node is root else ""
            return f'<li><details{opened}><summary>{label}</summary><ul>{children}</ul></details></li>'
        return f'<li>{label}</li>'
    return '<figure class="figure" id="fig-object-tree"><div class="figure-head"><span class="figure-label">Figure 1</span><p class="figure-title">Objects become folders; leaves stay on their parent page</p><span class="src">Observed structure</span></div><div class="figure-body"><div class="explorer-tree"><ul>' + branch(root) + '</ul></div><div class="explorer-map-legend"><span><code>object/</code> opens a folder page</span><span>Disclosure triangles expand nested objects</span><span>Leaf keys open numbered sections</span></div></div><p class="figure-caption">This tree is built from the sanitized content model. Its native disclosures work without JavaScript. Placeholder folders describe families of entries without exposing the original identifying keys.</p></figure>'


def search_index(root: dict, nodes: list[dict]) -> str:
    rows = []
    for node in nodes:
        entries = [(node, rel_link(root, node), "object", node.get("summary"))]
        entries += [(leaf, rel_link(root, node, leaf["anchor"]), "leaf", leaf.get("meaning")) for leaf in node["leaves"]]
        for item, href, kind, summary in entries:
            searchable = " ".join([str(item["key"]), item["path"], type_text(item.get("type")), text(summary)])
            rows.append(f'<li data-search="{esc(searchable)}"><a href="{esc(href)}"><code>{esc(item["path"])}</code></a> <small>{kind} · {esc(type_text(item.get("type")))}</small></li>')
    return '<p>The index searches the published structure and explanations. It does not load the source state file. Filtering changes this index only; all numbered sections remain readable.</p><div class="explorer-search" role="search"><label for="key-filter">Find a key or meaning</label><input id="key-filter" type="search" autocomplete="off" placeholder="Key, path, or explanation" aria-controls="explorer-search-index"/><span class="explorer-search-status" id="key-filter-status" aria-live="polite"></span></div><ol class="explorer-index" id="explorer-search-index">' + "".join(rows) + "</ol>"


def source_section(content: dict, sources: dict) -> str:
    body = paragraphs(content.get("provenance"), "The content model separates observed structure from documented or inferred meaning. No primitive values are reproduced by this renderer.")
    if sources:
        body += '<ol class="explorer-source-list">'
        for ref in sources.values():
            label = f'[{ref["id"]}] {ref.get("title") or ref["id"]}'
            url = ref.get("url")
            if url and urlparse(str(url)).scheme in ("http", "https"):
                heading = f'<a href="{esc(url)}">{esc(label)}</a>'
            else:
                heading = esc(label)
            detail = f'<p><code>{esc(ref["path"])}</code></p>' if ref.get("path") else ""
            if ref.get("locator"):
                detail += f'<p><strong>Locator:</strong> <code>{esc(text(ref["locator"]))}</code></p>'
            body += f'<li id="{esc(source_id(ref))}"><strong>{heading}</strong>{detail}{paragraphs(ref.get("note"))}</li>'
        body += "</ol>"
    return body


def page_sources(node: dict, sources: dict) -> dict:
    if node["parent"] is None:
        return sources
    used = set()
    for item in [node, *node["leaves"]]:
        used.update(text_parts(item.get("source")))
    return {key: ref for key, ref in sources.items() if key in used}


def breadcrumbs(node: dict, root: dict, content: dict) -> str:
    ancestors = []
    current = node["parent"]
    while current:
        ancestors.append(current)
        current = current["parent"]
    items = [f'<li><a href="{esc(site_link(node, "codex-session/index.html"))}">Anatomy of a Codex session</a></li>']
    for ancestor in reversed(ancestors):
        label = content.get("source_name") if ancestor is root else ancestor["key"]
        items.append(f'<li><a href="{esc(rel_link(node, ancestor))}">{esc(label or ancestor["key"])}</a></li>')
    items.append(f'<li aria-current="page">{esc(content.get("source_name") or node["key"] if node is root else node["key"])}</li>')
    return '<nav class="explorer-crumbs" aria-label="Breadcrumb"><ol>' + "".join(items) + "</ol></nav>"


class WordCounter(HTMLParser):
    def __init__(self):
        super().__init__()
        self.ignored = 0
        self.parts = []

    def handle_starttag(self, tag, attrs):
        if tag in ("script", "style", "svg"):
            self.ignored += 1

    def handle_endtag(self, tag):
        if tag in ("script", "style", "svg"):
            self.ignored -= 1

    def handle_data(self, value):
        if not self.ignored:
            self.parts.append(value)


def word_count(body: str) -> int:
    parser = WordCounter()
    parser.feed(body)
    return len(re.findall(r"\S+", " ".join(parser.parts)))


def render_page(node: dict, root: dict, nodes: list[dict], content: dict, css: str, logo: str, paper_js: str, sources: dict) -> tuple[str, int]:
    sections = section_list(node, content)
    chrome, flow = navigation(sections)
    blocks = []
    for section in sections:
        kind = section["kind"]
        heading_text = f'<code>{esc(section["title"])}</code>' if kind == "leaf" else esc(section["title"])
        heading = f'<h2 id="{esc(section["id"])}"><span class="secnum">{section["number"]}</span>{heading_text}</h2>'
        if kind == "overview":
            body = (paragraphs(content.get("overview")) if node is root else "") + field_facts(node, sources, object_node=True)
        elif kind == "intro":
            item = section["content"]
            body = paragraphs(item.get("paragraphs"))
            if item.get("code"):
                body += f'<pre><code>{esc(item["code"])}</code></pre>'
            if item.get("source") or evidence_label(item):
                body += f'<p>{badge(evidence_label(item))} {evidence(item.get("source"), sources)}</p>'
        elif kind == "objects":
            body = object_index(node)
        elif kind == "tree":
            body = object_tree(root)
        elif kind == "search":
            body = search_index(root, nodes)
        elif kind == "leaf":
            body = field_facts(section["leaf"], sources)
        else:
            body = source_section(content, page_sources(node, sources))
        if kind in ("tree", "objects"):
            blocks.append(f'<section><div class="prose">{heading}</div>{body}</section>')
        else:
            cls = "prose explorer-field" if kind == "leaf" else "prose"
            blocks.append(f'<section class="{cls}">{heading}{body}</section>')
    footnote = text(content.get("provenance")) or "This explorer publishes sanitized structure and reviewed explanations. It does not modify the source file."
    article = "".join(blocks) + f'<p class="footnote">{esc(footnote)}</p>'
    words = word_count(article)
    minutes = max(1, math.ceil(words / 225))
    root_title = str(content.get("title") or "Codex JSON, key by key")
    title = root_title if node is root else f'{node["key"]} · {content.get("source_name") or "Codex JSON"}'
    description = text(node.get("summary")) or root_title
    canonical = f"{SITE}/{URL_ROOT}/" + (node["folder"].as_posix() + "/" if node["folder"].parts else "")
    heading = esc(root_title) if node is root else f'<span class="explorer-title-key">{esc(node["key"])}</span>'
