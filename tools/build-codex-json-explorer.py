def thumbnail(root: dict) -> str:
    """Reduce the actual first object-tree branch to the shared 320×160 card."""
    children = root["children"][:3]
    y_positions = [65 + 28 * i for i in range(max(1, len(children)))]
    pieces = ['<svg xmlns="http://www.w3.org/2000/svg" width="320" height="160" viewBox="0 0 320 160" role="img" aria-labelledby="title">' + GENERATED_MARK + '<title id="title">Codex JSON object tree</title><rect width="320" height="160" fill="#f7f7f5"/><rect width="320" height="4" fill="#d98226"/><text x="16" y="26" fill="#777772" font-family="monospace" font-size="10" letter-spacing="1">CODEX / STATE REFERENCE</text>', '<rect x="18" y="61" width="83" height="31" rx="3" fill="#ffffff" stroke="#b8b8b1"/><text x="30" y="80" fill="#252525" font-family="monospace" font-size="11">object /</text>']
    for i, y in enumerate(y_positions):
        pieces.append(f'<path d="M101 76 H119 V{y + 8} H139" fill="none" stroke="#252525" stroke-width="1.6"/>')
        if children:
            child = children[i]
            pieces.append(f'<rect x="139" y="{y}" width="88" height="18" rx="2" fill="#ffffff" stroke="#b8b8b1"/>')
            leaf_count = min(3, len(child["leaves"]))
        else:
            pieces.append(f'<rect x="139" y="{y}" width="88" height="18" rx="2" fill="#f7e3c8" stroke="#d98226"/>')
            leaf_count = min(3, len(root["leaves"]))
        for j in range(leaf_count):
            pieces.append(f'<path d="M235 {y + 4 + j * 5} H{278 - j * 7}" stroke="#777772" stroke-width="2"/>')
    pieces.append('<text x="18" y="145" fill="#4f4f4b" font-family="monospace" font-size="10">folders → objects · sections → leaves</text></svg>')
    return "".join(pieces)


def write_owned(path: Path, value: str) -> None:
    if path.exists() and GENERATED_MARK not in path.read_text(encoding="utf-8")[:400]:
        raise ValueError(f"refusing to replace unowned page: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(value, encoding="utf-8")


def build(content_path: Path, out_dir: Path, base_path: Path) -> dict:
    content = json.loads(content_path.read_text(encoding="utf-8"))
    if not isinstance(content, dict) or "root" not in content:
        raise ValueError("content must be an object containing root")
    root, nodes = prepare_tree(content["root"])
    sources = {}
    for ref in content.get("sources", []):
        if not isinstance(ref, dict) or not ref.get("id"):
            raise ValueError("each source needs an id")
        if str(ref["id"]) in sources:
            raise ValueError(f"duplicate source id: {ref['id']}")
        sources[str(ref["id"])] = ref
    base = base_path.read_text(encoding="utf-8")
    css_match = re.search(r"<style[^>]*>(.*?)</style>", base, re.S)
    logo_match = re.search(r'<svg\b[^>]*class="xo-logo".*?</svg>', base, re.S)
    if not css_match or not logo_match:
        raise ValueError("base page must contain inline CSS and the XO logo")
    css, logo = css_match.group(1), logo_match.group(0)
    # Remove indentation on blank lines between inherited CSS blocks.
    css = re.sub(r"(?m)^[ \t]+$", "", css)
    paper_js = PAPER_JS.read_text(encoding="utf-8")
    rendered = []
    for node in nodes:
        page, words = render_page(node, root, nodes, content, css, logo, paper_js, sources)
        path = out_dir / node["folder"] / "index.html"
        if path.exists() and GENERATED_MARK not in path.read_text(encoding="utf-8")[:400]:
            raise ValueError(f"refusing to replace unowned page: {path}")
        rendered.append((path, page, words))
    thumb_path = out_dir / "assets" / "thumb.svg"
    if thumb_path.exists() and GENERATED_MARK not in thumb_path.read_text(encoding="utf-8")[:400]:
        raise ValueError(f"refusing to replace unowned thumbnail: {thumb_path}")
    # All input and ownership checks precede the first output mutation.
    written = set()
    for path, page, _ in rendered:
        write_owned(path, page)
        written.add(path.resolve())
    thumb_path.parent.mkdir(parents=True, exist_ok=True)
    thumb_path.write_text(thumbnail(root), encoding="utf-8")
    removed = 0
    prune_candidates = set()
    for path in out_dir.rglob("index.html"):
        if path.resolve() not in written and GENERATED_MARK in path.read_text(encoding="utf-8")[:400]:
            path.unlink()
            removed += 1
            candidate = path.parent
            while candidate != out_dir:
                prune_candidates.add(candidate)
                candidate = candidate.parent
    for path in sorted(prune_candidates, key=lambda p: len(p.parts), reverse=True):
        if path.is_dir() and not any(path.iterdir()):
            path.rmdir()
    return {"pages": len(nodes), "leaves": sum(len(n["leaves"]) for n in nodes), "rootWords": rendered[0][2], "rootReadingMinutes": max(1, math.ceil(rendered[0][2] / 225)), "removedOwnedPages": removed, "output": str(out_dir)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--content", type=Path, default=DEFAULT_CONTENT)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--base-page", type=Path, default=DEFAULT_BASE)
    args = parser.parse_args()
    try:
        result = build(args.content.resolve(), args.out.resolve(), args.base_page.resolve())
    except (ValueError, OSError, KeyError, TypeError) as error:
        parser.exit(1, f"error: {error}\n")
    print(json.dumps(result, ensure_ascii=False))


if __name__ == "__main__":
    main()
