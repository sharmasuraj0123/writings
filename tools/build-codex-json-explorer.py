"""Render the Codex JSON explorer without reading any private state file.

Input: codex-session/codex-json/_content.json, assembled from sanitized
structure and reviewed explanations. Output: one self-contained index.html
per object, with one real h2 section per direct leaf. Arrays containing
objects may be represented as nodes with an <item> child; scalar arrays are
leaves. The renderer never discovers or imports the user's Codex state.

Content contract (all prose is plain text and escaped):
  {title, source_name, source_path, snapshot, runtime,
   overview: [paragraph], provenance: [paragraph],
   intro_sections: [{id, title, paragraphs, code?, source?, evidence?}],
   sources: [{id, title, url?, path?, locator?, note?}],
   root: {key, path, type, summary, badge?, meaning?, behavior?, source?,
          limits?, presence?, children: [node],
          leaves: [{key, path, type, meaning, behavior?, source?, limits?,
                    badge?, presence?}]}}

Text fields accept a string or a list of paragraphs. `source` accepts a
source ID, a list of IDs, or plain explanatory text. Badges are typically
observed, bundle, documented, or inferred. Paths are sanitized JSON Pointers;
they supply stable identity, not filesystem locations. Extra fields survive
input validation but do not get published automatically.

The default output is the publication companion. --content and --out allow
temporary fixture builds without publishing invented research. Only stale
HTML bearing this renderer's ownership mark is removed during a rebuild.
"""

