def esc(s: str) -> str:
    return html.escape(s, quote=True)


def strip_tags(s: str) -> str:
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", s))).strip()


def load_content():
    sys.dont_write_bytecode = True  # never leave __pycache__ inside the published folder
    spec = importlib.util.spec_from_file_location("claude_json_content", CONTENT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def children(node):
    """Child nodes (folders) in the order they appear in the node's groups."""
    out = []
    for g in node.get("groups", []):
        for r in g["rows"]:
            if r.get("node"):
                out.append(r)
    return out


def walk(node, trail=()):
    """Yield (node, trail) where trail is the tuple of ancestor nodes."""
    yield node, trail
    for child in children(node):
        yield from walk(child, trail + (node,))


def rel_folder(trail, node):
    parts = [n["folder"] for n in trail[1:]] + ([node["folder"]] if trail else [])
    return "/".join(parts)


def breakable(key: str) -> str:
    """Escape a key and add <wbr> at camelCase and _ boundaries, so long keys
    wrap between words instead of mid-word."""
    out = esc(key)
    out = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "<wbr>", out)
    out = out.replace("_", "_<wbr>")
    return out


def key_html(row):
    if row.get("placeholder"):
        return f'<code class="ph">&lt;{esc(row["key"])}&gt;</code>'
    return f"<code>{breakable(row['key'])}</code>"


def render_row(row):
    rid = "k-" + (row.get("folder") if row.get("node") else re.sub(r"[^A-Za-z0-9_-]+", "-", row["key"]))
    badge = row.get("badge")
    badge_html = ""
    if badge:
        cls = "recon" if badge in ("inferred", "partly inferred") else "src"
        badge_html = f' <span class="{cls}">{esc(badge)}</span>'
    pres = f'<span class="pres">{row["presence"]}</span>' if row.get("presence") else ""
    note = f'<div class="note">{row["notes"]}</div>' if row.get("notes") else ""
    if row.get("node"):
        href = row["folder"] + "/"
        key = (f'<a class="dir" href="{esc(href)}">{key_html(row)}<span class="slash">/</span></a>')
        meaning = f'{row["summary"]}{badge_html} <a class="open" href="{esc(href)}">open &rarr;</a>{note}'
    else:
        key = key_html(row)
        meaning = f"{row['meaning']}{badge_html}{note}"
    return (
        f'            <tr id="{esc(rid)}" data-key="{esc(row["key"])}">'
        f'<td class="k">{key}</td><td class="t">{esc(row["type"])}{pres}</td>'
        f"<td>{meaning}</td></tr>"
    )


def render_group(g, idx, with_ids):
    gid = g.get("id") or f"group-{idx}"
    n = len(g["rows"])
    noun = "row" if any(r.get("placeholder") for r in g["rows"]) else "key"
    head = f'{esc(g["title"])}<span class="count">{n} {noun if n == 1 else noun + "s"}</span>' if g.get("count", True) else esc(g["title"])
    intro = f'\n          <p class="group-intro">{g["intro"]}</p>' if g.get("intro") else ""
    rows = "\n".join(render_row(r) for r in g["rows"])
    col = g.get("key_col", "Key")
    return f"""
        <section class="group" id="{esc(gid)}" aria-labelledby="{esc(gid)}-h">
          <h2 id="{esc(gid)}-h">{head}</h2>{intro}
          <div class="table-wrap">
            <table class="keys">
              <thead><tr><th scope="col">{esc(col)}</th><th scope="col">Type</th><th scope="col">What it holds</th></tr></thead>
              <tbody>
{rows}
              </tbody>
            </table>
          </div>
        </section>"""


def render_tree(node, prefix):
    def rec(n, pre):
        items = []
        for c in children(n):
            href = pre + c["folder"] + "/"
            label = (f'<span class="ph">&lt;{esc(c["key"])}&gt;</span>' if c.get("placeholder") else esc(c["key"]))
            sub = rec(c, href)
            items.append(
                f'<li><a href="{esc(href)}">{label}/</a> <span class="sum">{esc(strip_tags(c.get("tree_label") or c["summary"]))}</span>{sub}</li>'
            )
        return f"<ul>{''.join(items)}</ul>" if items else ""
    return rec(node, prefix)


