def main():
    content = load_content()
    root = content.ROOT
    written = set()
    for node, trail in walk(root):
        folder = rel_folder(trail, node)
        out_dir = os.path.join(OUT_DIR, folder) if folder else OUT_DIR
        os.makedirs(out_dir, exist_ok=True)
        path = os.path.join(out_dir, "index.html")
        text = page(node, trail, content)
        for ch in ("\u2014", "\u2013"):  # em and en dash, written as escapes
            if ch in text:
                i = text.index(ch)
                sys.exit(f"dash character in {path}: {text[max(0, i - 60):i + 20]!r}")
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        written.add(os.path.abspath(path))
    # delete stale generated pages, prune empty folders
    removed = 0
    for dirpath, dirnames, filenames in os.walk(OUT_DIR, topdown=False):
        for fn in filenames:
            p = os.path.abspath(os.path.join(dirpath, fn))
            if fn == "index.html" and p not in written:
                with open(p, encoding="utf-8") as f:
                    if GENERATED_MARK in f.read(400):
                        os.remove(p)
                        removed += 1
        if dirpath != OUT_DIR and not os.listdir(dirpath):
            os.rmdir(dirpath)
    print(f"wrote {len(written)} pages under {os.path.relpath(OUT_DIR, ROOT_DIR)}/, removed {removed} stale")


if __name__ == "__main__":
    main()
