    for b in node.get("after", []):
        bid = f' id="{esc(b["id"])}"' if b.get("id") else ""
        h = f'\n          <h2{bid}>{esc(b["title"])}</h2>' if b.get("title") else ""
        body = b["html"]
        if b.get("tree"):
            body = f'<div class="tree">{render_tree(node, "")}</div>'
        after.append(f'\n        <section class="prose">{h}\n          {body}\n        </section>')

